def build_item_candidates():
    candidates = []
    for kind, unlock_methods in (
        ("weapon", REBEL_DROP_WEAPONS),
        ("vehicle", REBEL_DROP_VEHICLES),
    ):
        for unlock_method, names in unlock_methods.items():
            for name in names:
                candidates.append(
                    {
                        "id": f"{kind}:{name}",
                        "name": name,
                        "display_name": name,
                        "category": kind,
                        "unlock_method": unlock_method,
                        "regions": ["Medici"],
                        "sources": [SOURCES["rebel_drop"]],
                    }
                )
    return candidates


def build_location_candidates():
    candidates = []

    def add(category, name, region, source, identifier=None):
        key = identifier or f"{category}:{region}:{name}"
        candidates.append(
            {
                "id": key,
                "name": name,
                "display_name": f"{category.replace('_', ' ').title()}: {name}",
                "category": category,
                "regions": [region],
                "sources": [source],
            }
        )

    for name in MILITARY_BASES:
        add("military_base", name, "Medici", SOURCES["military_bases"])
    for name in SETTLEMENTS:
        source = SOURCES["unnamed_town"] if name.startswith("Unnamed town") else SOURCES["towns"]
        add("settlement", name, "Medici", source)

    for day in DI_RAVELLO_TAPE_DAYS:
        add("di_ravello_tape", f"Day {day}", "Medici", SOURCES["tapes"])
    for name in EDEN_CALLAGHAN_TAPES:
        add(
            "eden_callaghan_tape",
            name,
            "Scolio",
            SOURCES["eden_tapes"],
        )

    for island, coordinates in SHRINES_BY_ISLAND.items():
        for coordinates_text in coordinates:
            add("rebel_shrine", coordinates_text, island, SOURCES["shrines"])
    for coordinates_text in ANCIENT_TOMB_COORDINATES:
        add(
            "ancient_tomb",
            coordinates_text,
            "Insula Striate",
            SOURCES["tombs"],
        )

    for name in STORY_MISSIONS:
        add("story_mission", name, "Medici", SOURCES["story_missions"])
    for name in DLC_MISSIONS:
        add("dlc_mission", name, "Medici", SOURCES["dlc_missions"])

    return candidates


